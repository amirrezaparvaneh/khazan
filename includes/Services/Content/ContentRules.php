        $focus = trim((string) $focus);
        return "[قواعد عنوان سئوی محصول]\n" .
            "۱. focus_keyword دقیقاً بین ۲ تا ۴ کلمه است و حتماً هم دسته‌بندی/نوع کالا و هم نام مدل محصول را دارد (مثل «نیم‌بوت چرم زنانه آلفردو» یا «کفش مردانه ونس فلوتر»)؛ فرمول: [نوع کالا] + [جنسیت] + [نام اختصاصی مدل]. کلمات طبیعی، تبریز، مدل، طرح، اصل، دست‌دوز، کد، فروش، خرید و قیمت هرگز در آن نیایند و جنسیت هرگز حذف نشود؛ فقط وقتی نام مدل ۱ کلمه‌ای است و جا برای ۴ کلمه هست، درست بعد از نوع کالا اول صفت کاربری (طبی، مجلسی، اسپرت، اداری، راحتی، کلاسیک) و در نبود آن «چرم/چرمی» می‌آید (مثل «کفش طبی مردانه مارکو» یا «بوت چرم زنانه آلفردو»؛ برای مدل ۲ کلمه‌ای «کفش مردانه ونس فلوتر» بدون صفت اضافه). هرگز کل نام محصول یا عبارت ناقص بدون مدل نیست." . ($focus !== '' ? " برای این محصول: «" . $focus . "»." : '') . "\n" .

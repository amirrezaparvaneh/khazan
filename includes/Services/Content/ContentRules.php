            "۱۰. ساختار پاراگراف: هر پاراگراف الزاماً داخل تگ صریح <p>...</p> باشد (متن آزاد یا جداسازی فقط با خط خالی ممنوع است) و طول هر <p> حداکثر ۶۰ تا ۹۰ کلمه (۳ تا ۴ جمله کوتاه) باشد؛ پاراگراف بلندتر را به چند <p> بشکن. هرگز بیش از ۱۱۰ کلمه بین دو تگ متوالی ننویس.\n" .

final class ContentRules {

    /**
     * قوانین قالب HTML، توزیع کلیدواژه و نگارش فعال؛ برای محصول، دسته‌بندی و مقاله یکسان است
     */
    public static function writing_rules($kind) {
        $tags = $kind === Settings::KIND_PRODUCT
            ? 'فقط از <h2>، <h3>، <p>، <ul>، <li>، <strong> و <a> استفاده کن. تگ <table> و هر تگ جدولی ممنوع است؛ مشخصات فنی را به‌صورت <ul><li><strong>ویژگی:</strong> مقدار</li></ul> بنویس.'
            : 'از <h2>، <h3>، <p>، <ul>، <li>، <strong> و <a> استفاده کن.';
        return "[قوانین قالب و نگارش]\n" .
            "۱. HTML فشرده بنویس: هر تگ روی همان خط، بدون خط خالی یا فاصله بین تگ‌های بلاک. " . $tags . "\n" .
            "۲. پرسش‌های متداول را با ساختار <h3>سوال</h3><p>پاسخ</p> بنویس.\n" .
            "۳. تعداد تکرار کلیدواژه کانونی در کل متن دقیقاً بین ۳ تا حداکثر ۵ بار باشد؛ هرگز بیشتر از ۵ بار. بقیه موارد را با مترادف‌ها بیاور. توزیع باید کاملاً متوازن باشد (Yoast متن را به بخش‌های مساوی تقسیم می‌کند و بخش بدون کلیدواژه یا مترادف خطا می‌گیرد): ۱ بار کلیدواژه کانونی در پاراگراف اول، ۱ بار یکی از مترادف‌ها در اواسط متن (بخش بررسی متریال/رویه)، ۱ بار کلیدواژه کانونی یا مترادف در بخش مزایا/ویژگی‌ها، و ۱ بار در سوالات متداول یا پاراگراف پایانی. از تجمع کلیدواژه‌ها در یک بخش و خالی ماندن بخش‌های دیگر اکیداً خودداری کن؛ هیچ بخش بلندی نباید بدون کلیدواژه یا مترادف بماند.\n" .
            "۴. فاصله بین دو زیرسرفصل (H2/H3) نباید بیشتر از ۲۲۰ واژه باشد.\n" .
            "۵. حتماً ۱ لینک خارجی معتبر و مرتبط با موضوع متن در جای مناسب قرار بده؛ منابع می‌توانند مقالات تخصصی، سایت‌های مرجع صنعت مربوطه، مستندات رسمی یا ویکی‌پدیا باشند. با تگ <a href=\"URL\" target=\"_blank\" rel=\"noopener\"> بنویس. URL باید واقعی و قابل اتکا باشد؛ لینک حدسی یا ساختگی نساز. انکرتکست باید دقیقاً روی یک واژه یا عبارت تخصصی که خودِ جمله به آن اشاره دارد (مثل نام یک استاندارد، متریال یا مفهوم فنی) قرار بگیرد، مثلاً «...طبق <a ...>استانداردهای جهانی ارگونومی پا</a> طراحی شده...». عبارت‌های عمومی و ماشینی مثل «اینجا»، «این مرجع»، «به این مرجع مراجعه کنید» یا «کلیک کنید» ممنوع است.\n" .
            "۶. قانون دقیق زیرعنوان‌ها: اگر متن N زیرعنوان (H2 و H3) دارد، دقیقاً بین ۳۰٪ تا ۵۰٪ آن‌ها (مثلاً در متنی با ۴ تا ۶ زیرعنوان، دقیقاً ۲ زیرعنوان) باید «کلیدواژه کانونی» یا دقیقاً یکی از «عبارات کلیدی مترادف و فرعی ثبت‌شده» را کلمه‌به‌کلمه و بدون تغییر در خود هدینگ داشته باشند. بقیه زیرعنوان‌ها (۵۰٪ تا ۷۰٪) را کاملاً بدون کلیدواژه کانونی و بدون عبارات مترادف بنویس تا هم کمبود کلیدواژه در زیرعنوان و هم بهینه‌سازی بیش‌ازحد (Over-optimization) صفر شود.\n" .
            "۷. نگارش فعال: اکیداً از جملات مجهول فارسی (ساخته شده است، تولید می‌شود، طراحی گردیده است، استفاده شده است، به کار رفته است) پرهیز کن و حداکثر ۵٪ جمله‌ها مجهول باشند. جمله‌ها را معلوم بنویس. مثال غلط: «رویه از چرم طبیعی ساخته شده است». مثال درست: «تولیدکنندگان در بخش رویه از چرم طبیعی گاوی استفاده کرده‌اند» یا «رویه چرم طبیعی گاوی، دوام این کفش را تضمین می‌کند».\n" .
            "۸. کلیدواژه کانونی (focus_keyword) دقیقاً ۲ تا ۴ کلمه است، شامل دسته‌بندی اصلی و مدل/ویژگی شاخص (مثل «کفش مردانه ونس فلوتر») و هرگز کل نام محصول نیست. تمام لینک‌های داخلی، چه به صفحه دیگر و چه از صفحه دیگر، با انکرتکست کوتاه و هدفمند حداکثر ۴ کلمه‌ای ساخته شوند؛ انکر هرگز نام کامل محصول یا یک جمله نباشد.\n";
    }

    /**
     * قواعد مشترک عنوان سئو: کلیدواژه در ابتدا، یک ایموجی مرتبط، طول مناسب و بدون نام سایت
     */
    public static function seo_title_rules($kind) {
        if ($kind === Settings::KIND_PRODUCT) return self::product_seo_title_rules();
        $modifiers = array(
            Settings::KIND_ARTICLE  => 'یک مزیت یا نوع محتوا مانند «راهنمای کامل»، «آموزش گام‌به‌گام» یا «روش‌ها»',
            Settings::KIND_CATEGORY => 'یک کلمه تجاری مانند «خرید»، «قیمت» یا «انواع» همراه گستره محصولات همان دسته',
        );
        return "[قواعد عنوان سئو]\n" .
            "۱. طول عنوان (با احتساب ایموجی و فاصله‌ها) ۵۰ تا ۶۰ کاراکتر باشد و از ۶۰ بیشتر نشود تا در نتایج گوگل بریده نشود.\n" .
            "۲. عبارت کانونی دقیقاً و بدون تغییر، در ابتدای عنوان بیاید؛ سپس " . $modifiers[$kind] . " اضافه شود. عنوان باید با محتوای واقعی صفحه و نیت جستجو سازگار باشد و وعده‌ای (تخفیف، ارسال رایگان، رتبه یک و ...) که تایید نشده نباشد.\n" .
            "۳. دقیقاً یک ایموجی مرتبط با موضوع در ابتدا یا انتهای عنوان بگذار؛ نه وسط عنوان، نه بیش از یکی و نه ایموجی نامرتبط یا تزئینی. جداکننده بخش‌ها «|» یا «–» باشد.\n" .
            "۴. نام سایت را اضافه نکن (یوست آن را از قالب سراسری اضافه می‌کند). تکرار کلیدواژه، کلمات پرکننده، حروف درشت لاتین و تیتر کلیک‌طعمه ممنوع است.\n" .
            "۵. توضیحات متا ۱۴۰ تا ۱۶۰ کاراکتر، شامل عبارت کانونی یک‌بار، مزیت اصلی و یک دعوت به اقدام طبیعی باشد.\n";
    }

    /**
     * فرمول عنوان سئوی محصول: [نوع کالا + جنس + جنسیت + مدل] | [مزیت/اصالت + ایموجی] | [برند]
     */
    public static function product_seo_title_rules() {
        $brand = Settings::brand_name();
        $emojis = array();
        foreach (Settings::SEO_TITLE_EMOJIS as $entry) $emojis[] = $entry[0] . ' ' . implode('/', $entry[1]);
        return "[قواعد عنوان سئوی محصول]\n" .
            "۱. seo_title دقیقاً سه بخش با جداکننده « | » دارد: [نوع کالا + جنس + جنسیت + نام مدل] | [مزیت یا اصالت تولید + یک ایموجی] | [" . ($brand !== '' ? $brand : 'نام برند') . "]. نمونه: «نیم‌بوت چرم زنانه آلفردو | چرم طبیعی تبریز 👢 | " . ($brand !== '' ? $brand : 'آکا چرم') . "».\n" .
            "۲. بخش اول فقط نوع کالا، جنس، جنسیت و نام مدل است (مثل «کیف دوشی چرم مردانه آرتین») و کلمات زائد مثل روزمره، طرح جدید، اصل و تضمینی ندارد.\n" .
            "۳. بخش دوم یک مزیت یا اصالت واقعی و تاییدشده در داده‌هاست (مثل «چرم طبیعی تبریز»، «دست‌دوز تبریز»، «چرم ۱۰۰٪ طبیعی») و در انتهایش دقیقاً یک ایموجی متناسب با دسته می‌آید. ایموجی‌های مجاز: " . implode('، ', $emojis) . ".\n" .
            "۴. بخش سوم دقیقاً نام برند «" . ($brand !== '' ? $brand : 'نام برند') . "» است و حذف یا تغییر نمی‌کند.\n" .
            "۵. طول کل عنوان (با ایموجی و فاصله‌ها) ۵۰ تا ۶۰ کاراکتر و هرگز بیشتر از ۶۰ کاراکتر نباشد تا در نتایج گوگل (SERP) بریده نشود؛ برای کوتاه‌کردن، بخش مزیت را خلاصه کن نه کلیدواژه را.\n" .
            "۶. توضیحات متا ۱۴۰ تا ۱۶۰ کاراکتر، شامل عبارت کانونی یک‌بار، مزیت اصلی و یک دعوت به اقدام طبیعی باشد.\n";
    }

    /**
     * الگوی ثابت ساختار محصول؛ در تولید تکی و انبوه یکسان است و متن هر محصول باید مختص خودش باشد
     */
    public static function product_blueprint() {
        return "[ساختار ثابت محصول - در همه محصولات رعایت شود؛ جمله‌ها و قلاب‌ها را برای هر محصول متفاوت بنویس]\n" .
            "۱. مقدمه (یک پاراگراف کوتاه): یک قلاب جذاب، بیان مشکل یا نیاز کاربر، و معرفی محصول همراه با کلیدواژه کانونی.\n" .
            "۲. H2 «بررسی تخصصی رویه و زیره» (۲ تا ۳ پاراگراف کوتاه): تحلیل متریال، دوام و راحتی فقط بر اساس داده‌های شیت (زیره، رویه، آستر و ویژگی‌های کلی). داده‌ای که در شیت نیست را ننویس.\n" .
            "۳. H2 «مزایا و ارزش خرید»: فهرست <ul><li> با بالت‌لاین‌های کوتاه از ویژگی‌های کلیدی.\n" .
            "۴. H2 «سوالات متداول»: ۲ تا ۳ پرسش کلیدی، هر کدام با ساختار <h3>سوال</h3><p>پاسخ کوتاه</p>.\n" .
            "H1 و بخش اضافه نساز. عنوان هدینگ‌ها را طبیعی بنویس و طبق قانون ۶ طبق قانون ۶ فقط ۳۰٪ تا ۵۰٪ آن‌ها کلیدواژه کانونی یا مترادف ثبت‌شده داشته باشند.\n";
    }

    /**
     * عبارت کلیدی کوتاه از نام محصول: حذف «مدل ...» و کدهای انتهایی، و نگه‌داشتن حداکثر ۴ کلمه
     */
    public static function short_keyword($title) {
        $title = trim(preg_replace('/\s+/u', ' ', (string) $title));
        if ($title === '') return '';
        $base = trim(preg_split('/(?:^|\s+)مدل(?:\s|$)/u', $title)[0]);
        $words = array_values(array_filter(explode(' ', $base), 'strlen'));
        // کدهای مدل مانند «V2» یا «۱۲۳-AB» در انتها معمولاً مفهوم جستجو ندارند.
        while ($words && preg_match('/[0-9A-Za-z\x{0660}-\x{0669}\x{06F0}-\x{06F9}]/u', end($words))) array_pop($words);
        if (!$words) return $title;
        return implode(' ', array_slice($words, 0, 4));
    }
}

            "۳. بخش اول فقط و دقیقاً focus_keyword است؛ هیچ کلمه اضافه (روزمره، طرح جدید، اصل، تضمینی) یا حذف نام مدل در آن مجاز نیست.\n" .
            "۴. بخش دوم فقط یک مزیت واقعی و تأییدشده است (مثل «اقساط ۴ مرحله‌ای»)؛ ایموجی، «ارسال رایگان» و ادعای تأییدنشده ممنوع است.\n" .

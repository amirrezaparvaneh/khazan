    /**
     * قانون سخت‌گیرانه تکرار دقیق کلیدواژه کانونی مقاله (Exact Match): ۴ تا ۶ بار بسته به طول متن
     */
    public static function article_keyword_rule($word_count = 0) {
        $words = max(0, (int) $word_count);
        $min = max(1, (int) ceil($words * SeoStandards::get('density_min') / 100));
        $max = max($min, (int) floor($words * SeoStandards::get('density_max') / 100));
        return "کلیدواژه کانونی را عیناً و دقیقاً با همان شکل و ترتیب کلمات (Exact Match، نه فقط بخشی از آن) حداقل {$min} بار و حداکثر {$max} بار (چگالی " . SeoStandards::get('density_min') . " تا " . SeoStandards::get('density_max') . " درصد) به‌صورت طبیعی در متن بیاور. حضور دقیق آن در این جاها الزامی است: ۱۰۰ واژه نخست، حداقل یک زیرعنوان H2 (و حداکثر " . SeoStandards::get('h2_keyword_max') . " زیرعنوان H2)، میانه محتوا و پاراگراف نتیجه‌گیری. بقیه موارد را با مترادف‌ها بیاور. ";
    }

    public static function writing_rules($kind, $word_count = 0) {
        $tags = $kind === Settings::KIND_PRODUCT
            ? 'فقط از <h2>، <h3>، <p>، <ul>، <li>، <strong>، <a> و برای جدول مشخصات از <table>، <thead>، <tbody>، <tr>، <th>، <td> استفاده کن. جدول فقط یک‌بار و فقط با داده‌های تأییدشده شیت ساخته می‌شود، فقط متن ساده دارد و لینک در آن نیست.'
            : 'از <h2>، <h3>، <p>، <ul>، <li>، <strong> و <a> استفاده کن.';
        $density = $kind === Settings::KIND_ARTICLE
            ? self::article_keyword_rule($word_count)
            : "چگالی کلیدواژه کانونی بین " . SeoStandards::get('density_min') . " تا " . SeoStandards::get('density_max') . " درصد کل واژه‌ها باشد (بیشتر از سقف نه)؛ بقیه موارد را با مترادف‌ها بیاور. ";
        return "[قوانین قالب و نگارش]\n" .
            "۱. HTML فشرده بنویس: هر تگ روی همان خط، بدون خط خالی یا فاصله بین تگ‌های بلاک. " . $tags . "\n" .
            "۲. پرسش‌های متداول را با ساختار <h3>سوال</h3><p>پاسخ</p> بنویس.\n" .
            "۳. " . $density . "توزیع باید کاملاً متوازن باشد (Yoast متن را به بخش‌های مساوی تقسیم می‌کند و بخش بدون کلیدواژه یا مترادف خطا می‌گیرد): ۱ بار کلیدواژه کانونی در پاراگراف اول، ۱ بار یکی از مترادف‌ها در اواسط متن (بخش بررسی متریال/رویه)، ۱ بار کلیدواژه کانونی یا مترادف در بخش مزایا/ویژگی‌ها، و ۱ بار در سوالات متداول یا پاراگراف پایانی. از تجمع کلیدواژه‌ها در یک بخش و خالی ماندن بخش‌های دیگر اکیداً خودداری کن؛ هیچ بخش بلندی نباید بدون کلیدواژه یا مترادف بماند.\n" .
            "۴. فاصله بین دو زیرسرفصل (H2/H3) نباید بیشتر از ۲۲۰ واژه باشد.\n" .
            self::external_link_rule() .
            "۶. قانون زیرعنوان‌ها: کلیدواژه کانونی را در حداقل یک زیرعنوان و در حداکثر " . SeoStandards::get('h2_keyword_max') . " زیرعنوان H2 بیاور؛ بقیه زیرعنوان‌ها بدون کلیدواژه کانونی و با مترادف یا موضوع خود بخش نوشته شوند. حداقل " . SeoStandards::get('h2_min') . " زیرعنوان H2 داشته باش.\n" .
            "۷. نگارش فعال: اکیداً از جملات مجهول فارسی (ساخته شده است، تولید می‌شود، طراحی گردیده است، استفاده شده است، به کار رفته است) پرهیز کن و حداکثر ۵٪ جمله‌ها مجهول باشند. جمله‌ها را معلوم بنویس. مثال غلط: «رویه از چرم ساخته شده است». مثال درست: «رویه این مدل از چرم است و ظاهر مرتبی دارد». ادعاهایی مثل نوع چرم، دست‌دوز یا تبریز را فقط وقتی بنویس که در داده‌های ورودی باشد.\n" .

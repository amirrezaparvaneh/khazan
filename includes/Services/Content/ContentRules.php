            "۳ تا ۶ عبارت واقعی که کاربر ایرانی برای همین محصول جست‌وجو می‌کند، با ویرگول جدا شده و هر کدام ۲ تا ۴ کلمه؛ مثلاً نوع دیگر نام‌گذاری همان کالا، ترکیب با جنس یا کاربرد («بوت چرم زنانه»، «نیم‌بوت چرمی بانوان»). " .

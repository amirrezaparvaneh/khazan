    /**
     * عبارت کلیدی کوتاه از نام محصول: حذف «مدل ...» و کدهای انتهایی، و نگه‌داشتن حداکثر ۴ کلمه
     */
    public static function short_keyword($title) {
        $title = trim(preg_replace('/\s+/u', ' ', (string) $title));
        if ($title === '') return '';
        $base = trim(preg_split('/(?:^|\s+)مدل(?:\s|$)/u', $title)[0]);
        $words = array_values(array_filter(explode(' ', $base), 'strlen'));
        // کدهای مدل مانند «V2» یا «۱۲۳-AB» در انتها معمولاً مفهوم جستجو ندارند.
        while ($words && preg_match('/[0-9A-Za-z\x{0660}-\x{0669}\x{06F0}-\x{06F9}]/u', end($words))) array_pop($words);
        if (!$words) return $title;
        return implode(' ', array_slice($words, 0, 4));
    }

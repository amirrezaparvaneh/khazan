            "۶. طول کل عنوان (با فاصله‌ها) ۵۰ تا ۶۰ کاراکتر و هرگز بیشتر از ۶۰ کاراکتر نباشد تا در نتایج گوگل (SERP) بریده نشود؛ برای کوتاه‌کردن بخش مزیت را خلاصه کن، نه کلیدواژه را.\n" .
            "۷. توضیحات متا ۱۴۰ تا ۱۵۵ کاراکتر، شامل عبارت کانونی یک‌بار، مزیت اصلی و یک دعوت به اقدام طبیعی باشد.\n";
    }


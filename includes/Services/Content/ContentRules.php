        );
        return "[قواعد عنوان سئو]\n" .
            "۱. طول عنوان (با فاصله‌ها) ۵۰ تا ۶۰ کاراکتر باشد و از ۶۰ بیشتر نشود تا در نتایج گوگل بریده نشود.\n" .
            "۲. عبارت کانونی دقیقاً و بدون هیچ تغییری (عین رشته focus_keyword) در ابتدای عنوان بیاید؛ سپس " . $modifiers[$kind] . " اضافه شود. عنوان باید با محتوای واقعی صفحه و نیت جستجو سازگار باشد و وعده‌ای (تخفیف، ارسال رایگان، رتبه یک و ...) که تایید نشده نباشد.\n" .
            "۳. ایموجی در عنوان ممنوع است. قالب: [عبارت کانونی]؛ [قلاب/ارزش افزوده] | [نام برند]. عبارت «ارسال رایگان» در عنوان نیاید.\n" .
            "۴. نام کوتاه برند را فقط به‌عنوان آخرین بخش بعد از « | » بیاور و فقط اگر در ۶۰ کاراکتر جا شود؛ تکرار کلیدواژه، کلمات پرکننده، حروف درشت لاتین و تیتر کلیک‌طعمه ممنوع است.\n" .

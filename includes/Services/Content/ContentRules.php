    /**
     * سقف و یکتایی لینک‌ها در متن محصول: ۱ دسته‌بندی + ۱ خارجی + ۲ محصول مرتبط، هر URL فقط یک‌بار
     */
    public static function product_link_rules() {
        return "۱۱. قانون لینک‌ها در متن محصول: فقط لینک‌هایی را بگذار که در فهرست لینک‌های اجباری داده شده‌اند (دسته‌بندی اصلی و محصولات مرتبط) و لینک خارجی فقط از منابع تأییدشده (در صورت وجود). هر URL فقط یک‌بار در کل محتوا و هر پاراگراف حداکثر ۲ لینک. اگر نام محصول یا دسته در بخش‌های بعدی (مزایا، مشخصات، پرسش‌های متداول) دوباره آمد، لینک نشود و فقط متن ساده باشد.\n";
    }

    /**
     * External links: only from sources the owner verified (BusinessFacts); with none configured the text carries none.
     */
    public static function external_link_rule() {
        $sources = BusinessFacts::verified_sources();
        if (!$sources) {
            return "۵. لینک خارجی نساز؛ هیچ منبع تأییدشده‌ای ثبت نشده و لینک حدسی یا ساختگی ممنوع است.\n";
        }
        list(, $max) = SeoStandards::external_range();
        $lines = array();
        foreach ($sources as $src) $lines[] = $src['url'] . ($src['title'] !== '' ? ' (' . $src['title'] . ')' : '');
        return "۵. حداکثر " . $max . " لینک خارجی و فقط از این منابع تأییدشده، با <a href=\"URL\" target=\"_blank\" rel=\"noopener\"> و انکر توصیفی مرتبط با جمله (نه «اینجا» یا «کلیک کنید»):\n" . implode("\n", $lines) . "\n";
    }


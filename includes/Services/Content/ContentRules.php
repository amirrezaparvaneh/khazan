     */
    public static function seo_title_rules($kind, $focus = '') {
        if ($kind === Settings::KIND_PRODUCT) return self::product_seo_title_rules($focus);
        $modifiers = array(
            Settings::KIND_ARTICLE  => 'یک مزیت یا نوع محتوا مانند «راهنمای کامل»، «آموزش گام‌به‌گام» یا «روش‌ها»',
